# Criando uma lista de alunos
animais = ["Cachorro", "Gato", "Peixe"]

# Exibindo a lista completa
print(f"Lista de animais: {animais}")

# Acessando o primeiro animal (indice 0)
print(f"Primeiro animal: {animais[0]}")

# Acessando ultimo animal (indice -1)
print(f"Ultimo animal: {animais[-1]}")

# Adicionar: insere um novo animal no final da lista
animais.append("Hamster")
print(f"Lista atualizada: {animais}")

